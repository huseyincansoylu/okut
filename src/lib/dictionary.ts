/** Replaces `{name}` placeholders in a dictionary string. */
export function fill(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
}

/** Picks the English singular or plural form for `count`, then fills `{count}` and any other placeholders. */
export function plural(forms: { one: string; other: string }, count: number, values: Record<string, string | number> = {}) {
  return fill(count === 1 ? forms.one : forms.other, { count, ...values });
}

