import type { Metadata } from "next";
import { redirect } from "next/navigation";
import { Suspense } from "react";
import { requireUserId } from "@/lib/auth";
import { qrSvg } from "@/lib/qr";
import { getOwnedShop } from "@/lib/shops";
import { getMenuUrl } from "@/lib/site-url";
import { PrintButton } from "./print-button";

export const metadata: Metadata = { title: "Masa kartı" };

export default function QrPrintPage() {
  return (
    <Suspense fallback={<p className="p-6 text-sm text-muted-foreground">Yükleniyor...</p>}>
      <TableCard />
    </Suspense>
  );
}

async function TableCard() {
  const shop = await getOwnedShop(await requireUserId());
  if (!shop) redirect("/dashboard");

  const url = await getMenuUrl(shop.slug);
  const svg = await qrSvg(url);

  return (
    <main className="flex flex-1 flex-col items-center gap-6 p-6 print:p-0">
      <div className="flex items-center gap-3 print:hidden">
        <p className="text-sm text-muted-foreground">Kartı yazdırıp masalara koyabilirsin.</p>
        <PrintButton />
      </div>

      <article className="flex w-[10cm] flex-col items-center gap-4 rounded-2xl border bg-white p-8 text-center text-black print:break-inside-avoid">
        <h1 className="font-heading text-2xl font-bold">{shop.name}</h1>
        {/* Generated by the qrcode library from our own URL, so it is safe to inline. */}
        <div className="w-full [&_svg]:size-full" dangerouslySetInnerHTML={{ __html: svg }} />
        <p className="text-lg font-medium">Menü için QR kodu okutun</p>
        <p className="text-xs break-all text-neutral-500">{url}</p>
      </article>
    </main>
  );
}
