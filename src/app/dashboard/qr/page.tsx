import { LightbulbIcon } from "lucide-react";
import type { Metadata } from "next";
import Image from "next/image";
import { Suspense } from "react";
import { LogoMark } from "@/components/logo";
import { requireUserId } from "@/lib/auth";
import { dict } from "@/lib/dictionary";
import { qrSvg } from "@/lib/qr";
import { getOwnedShop } from "@/lib/shops";
import { getMenuUrl } from "@/lib/site-url";
import { NoShop } from "../_components/no-shop";
import { PageBody, PageHeader, PageSkeleton } from "../_components/page-header";
import { QrActions } from "../_components/qr-actions";
import { PrintButton } from "./print-button";

export const metadata: Metadata = { title: dict.dashboard.qr.title };

export default function QrPage() {
  return (
    <Suspense fallback={<PageSkeleton />}>
      <QrContent />
    </Suspense>
  );
}

async function QrContent() {
  const shop = await getOwnedShop(await requireUserId());
  if (!shop) return <NoShop />;
  const t = dict.dashboard.qr;

  const url = await getMenuUrl(shop.slug);
  const svg = await qrSvg(url);

  return (
    <PageBody>
      <div className="print:hidden">
        <PageHeader title={t.title} description={t.description} actions={<PrintButton />} />
      </div>

      <div className="grid items-start gap-6 lg:grid-cols-[1fr_1.1fr]">
        <div className="flex flex-col gap-6 print:hidden">
          <section className="rounded-3xl bg-card p-5 ring-1 ring-border/70 md:p-6">
            <QrActions url={url} svg={svg} slug={shop.slug} />
          </section>
          <section className="rounded-3xl bg-brand-tint/60 p-5 md:p-6">
            <h2 className="flex items-center gap-2 font-heading font-bold">
              <LightbulbIcon className="size-4 text-primary" />
              {t.tipsTitle}
            </h2>
            <ul className="mt-3 flex flex-col gap-2 text-sm text-muted-foreground">
              {t.tips.map((tip) => (
                <li key={tip} className="flex gap-2">
                  <span className="mt-2 size-1 shrink-0 rounded-full bg-primary" />
                  {tip}
                </li>
              ))}
            </ul>
          </section>
        </div>

        {/* Table card on a dotted "desk"; only the card itself is printed. */}
        <section className="relative isolate flex flex-col items-center gap-4 overflow-hidden rounded-3xl bg-muted/60 px-4 py-10 ring-1 ring-border/70 print:bg-transparent print:p-0 print:ring-0">
          <div className="absolute inset-0 -z-10 bg-dots opacity-70 print:hidden" />
          <p className="rounded-full bg-card px-3 py-1 text-xs font-medium text-muted-foreground shadow-sm ring-1 ring-border/70 print:hidden">
            {t.cardPreview}
          </p>
          <article className="flex w-[10cm] max-w-full flex-col items-center gap-4 rounded-3xl bg-white p-8 text-center text-black shadow-2xl shadow-black/15 ring-1 ring-black/5 print:break-inside-avoid print:shadow-none">
            {shop.logoUrl && <Image src={shop.logoUrl} alt="" width={64} height={64} className="size-16 object-contain" />}
            <h2 className="font-heading text-2xl font-bold">{shop.name}</h2>
            {/* Generated by the qrcode library from our own URL, so it is safe to inline. */}
            <div className="w-full [&_svg]:size-full" dangerouslySetInnerHTML={{ __html: svg }} />
            <p className="text-lg font-medium">{t.cardCta}</p>
            <p className="text-xs break-all text-neutral-500">{url}</p>
            <span className="inline-flex items-center gap-1 font-brand text-xs font-extrabold text-[#8C2413]">
              <LogoMark className="size-3" />
              okut
            </span>
          </article>
        </section>
      </div>
    </PageBody>
  );
}
