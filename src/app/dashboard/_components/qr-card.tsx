import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import type { Shop } from "@/db/schema";
import { qrSvg } from "@/lib/qr";
import { getMenuUrl } from "@/lib/site-url";
import { QrActions } from "./qr-actions";

export async function QrCard({ shop }: { shop: Pick<Shop, "name" | "slug"> }) {
  const url = await getMenuUrl(shop.slug);
  const svg = await qrSvg(url);

  return (
    <Card>
      <CardHeader>
        <CardTitle>QR kod</CardTitle>
        <CardDescription>Masalara koy; müşterilerin okutunca menün açılır.</CardDescription>
      </CardHeader>
      <CardContent className="flex flex-col gap-4 sm:flex-row sm:items-center">
        {/* Generated by the qrcode library from our own URL, so it is safe to inline. */}
        <div
          className="size-36 shrink-0 self-center rounded-lg bg-white p-2 [&_svg]:size-full"
          dangerouslySetInnerHTML={{ __html: svg }}
        />
        <QrActions url={url} svg={svg} slug={shop.slug} />
      </CardContent>
    </Card>
  );
}
