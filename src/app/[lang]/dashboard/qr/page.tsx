import type { Metadata } from "next";
import Image from "next/image";
import { Suspense } from "react";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { getDictionary } from "@/i18n/server";
import { requireUserId } from "@/lib/auth";
import { qrSvg } from "@/lib/qr";
import { getOwnedShop } from "@/lib/shops";
import { getMenuUrl } from "@/lib/site-url";
import { NoShop } from "../_components/no-shop";
import { PageBody, PageHeader, PageSkeleton } from "../_components/page-header";
import { LogoMark } from "@/components/logo";
import { QrActions } from "../_components/qr-actions";
import { PrintButton } from "./print-button";

export async function generateMetadata(): Promise<Metadata> {
  return { title: (await getDictionary()).dashboard.qr.title };
}

export default function QrPage() {
  return (
    <Suspense fallback={<PageSkeleton />}>
      <QrContent />
    </Suspense>
  );
}

async function QrContent() {
  const [shop, dict] = await Promise.all([requireUserId().then(getOwnedShop), getDictionary()]);
  if (!shop) return <NoShop />;
  const t = dict.dashboard.qr;

  const url = await getMenuUrl(shop.slug);
  const svg = await qrSvg(url);

  return (
    <PageBody>
      <div className="print:hidden">
        <PageHeader
          title={t.title}
          description={t.description}
          actions={<PrintButton />}
        />
      </div>

      <div className="grid items-start gap-6 lg:grid-cols-2">
        <Card className="print:hidden">
          <CardHeader>
            <CardTitle>{t.linkTitle}</CardTitle>
            <CardDescription>{t.linkText}</CardDescription>
          </CardHeader>
          <CardContent className="flex flex-col gap-4 sm:flex-row sm:items-center">
            {/* Generated by the qrcode library from our own URL, so it is safe to inline. */}
            <div
              className="size-32 shrink-0 self-center rounded-lg bg-white p-2 [&_svg]:size-full"
              dangerouslySetInnerHTML={{ __html: svg }}
            />
            <QrActions url={url} svg={svg} slug={shop.slug} />
          </CardContent>
        </Card>

        <section className="flex flex-col items-center gap-3">
          <p className="text-sm text-muted-foreground print:hidden">{t.cardPreview}</p>
          <article className="flex w-[10cm] max-w-full flex-col items-center gap-4 rounded-2xl border bg-white p-8 text-center text-black print:break-inside-avoid">
            {shop.logoUrl && (
              <Image src={shop.logoUrl} alt="" width={64} height={64} className="size-16 object-contain" />
            )}
            <h2 className="font-heading text-2xl font-bold">{shop.name}</h2>
            <div className="w-full [&_svg]:size-full" dangerouslySetInnerHTML={{ __html: svg }} />
            <p className="text-lg font-medium">{t.cardCta}</p>
            <p className="text-xs break-all text-neutral-500">{url}</p>
            <span className="inline-flex items-center gap-1 font-brand text-xs font-extrabold text-[#8C2413]">
              <LogoMark className="size-3" />
              okut
            </span>
          </article>
        </section>
      </div>
    </PageBody>
  );
}
