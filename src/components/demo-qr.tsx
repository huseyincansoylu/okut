import { ArrowRightIcon, ScanLineIcon } from "lucide-react";
import { cacheLife } from "next/cache";
import Link from "next/link";
import { buttonVariants } from "@/components/ui/button";
import { fill } from "@/i18n/config";
import { getDictionary, getLocale } from "@/i18n/server";
import { DEMO_SHOP } from "@/lib/demo";
import { qrSvg } from "@/lib/qr";
import { siteOrigin } from "@/lib/site-url";

/** Landing page section: a scannable QR code for the demo shop's live menu. */
export async function DemoQr() {
  "use cache";
  cacheLife("max");

  const [locale, dict] = await Promise.all([getLocale(), getDictionary()]);
  const t = dict.landing;
  // No language prefix in the QR: the proxy adds it when the phone opens the link.
  const path = `/menu/${DEMO_SHOP.slug}`;
  const svg = await qrSvg(`${siteOrigin()}${path}`);

  return (
    <section className="grid items-center gap-8 rounded-3xl bg-card p-8 ring-1 ring-border/70 md:grid-cols-[auto_1fr] md:p-10">
      {/* Generated by the qrcode library from our own URL, so it is safe to inline. */}
      <div
        className="mx-auto size-48 rounded-2xl bg-white p-3 ring-1 ring-border [&_svg]:size-full"
        dangerouslySetInnerHTML={{ __html: svg }}
      />
      <div className="flex flex-col gap-4 text-center md:text-left">
        <p className="flex items-center justify-center gap-2 text-sm font-medium text-primary md:justify-start">
          <ScanLineIcon className="size-4" />
          {t.demoBadge}
        </p>
        <h2 className="font-heading text-3xl font-extrabold tracking-tight">{t.demoTitle}</h2>
        <p className="max-w-md text-muted-foreground">{fill(t.demoText, { shop: DEMO_SHOP.name })}</p>
        <Link
          href={`/${locale}${path}`}
          target="_blank"
          className={buttonVariants({ variant: "outline", className: "self-center md:self-start" })}
        >
          {t.demoOpen}
          <ArrowRightIcon />
        </Link>
      </div>
    </section>
  );
}
