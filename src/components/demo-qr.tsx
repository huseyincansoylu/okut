import { ArrowRightIcon, ScanLineIcon } from "lucide-react";
import { cacheLife } from "next/cache";
import Link from "next/link";
import { buttonVariants } from "@/components/ui/button";
import { DEMO_SHOP } from "@/lib/demo";
import { qrSvg } from "@/lib/qr";
import { siteOrigin } from "@/lib/site-url";

/** Landing page section: a scannable QR code for the demo shop's live menu. */
export async function DemoQr() {
  "use cache";
  cacheLife("max");

  const path = `/menu/${DEMO_SHOP.slug}`;
  const svg = await qrSvg(`${siteOrigin()}${path}`);

  return (
    <section className="grid items-center gap-8 rounded-2xl border p-8 md:grid-cols-[auto_1fr] md:p-10">
      {/* Generated by the qrcode library from our own URL, so it is safe to inline. */}
      <div
        className="mx-auto size-48 rounded-xl bg-white p-3 shadow-sm ring-1 ring-black/5 [&_svg]:size-full"
        dangerouslySetInnerHTML={{ __html: svg }}
      />
      <div className="flex flex-col gap-4 text-center md:text-left">
        <p className="flex items-center justify-center gap-2 text-sm font-medium opacity-70 md:justify-start">
          <ScanLineIcon className="size-4" />
          Canlı demo
        </p>
        <h2 className="text-2xl font-semibold">Telefonunla okut, menüyü gör</h2>
        <p className="max-w-md opacity-70">
          Kameranı QR koda tut; {DEMO_SHOP.name}&apos;nin menüsü müşterilerinin göreceği haliyle açılsın. Uygulama
          indirmeye ya da kayıt olmaya gerek yok.
        </p>
        <Link
          href={path}
          target="_blank"
          className={buttonVariants({ variant: "outline", className: "self-center md:self-start" })}
        >
          Menüyü bu cihazda aç
          <ArrowRightIcon />
        </Link>
      </div>
    </section>
  );
}
