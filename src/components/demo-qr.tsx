import { ArrowRightIcon, ScanLineIcon } from "lucide-react";
import { cacheLife } from "next/cache";
import Link from "next/link";
import { buttonVariants } from "@/components/ui/button";
import { DEMO_SHOP } from "@/lib/demo";
import { dict, fill } from "@/lib/dictionary";
import { qrSvg } from "@/lib/qr";
import { siteOrigin } from "@/lib/site-url";

const DEMO_PATH = `/menu/${DEMO_SHOP.slug}`;

/** The demo shop's QR code on a white tile, sized by `className`. */
export async function DemoQrCode({ className = "" }: { className?: string }) {
  "use cache";
  cacheLife("max");

  const svg = await qrSvg(`${siteOrigin()}${DEMO_PATH}`);
  return (
    // Generated by the qrcode library from our own URL, so it is safe to inline.
    <div
      className={`rounded-2xl bg-white p-2.5 text-black [&_svg]:size-full ${className}`}
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}

/** Corner brackets of a camera viewfinder. */
function Viewfinder() {
  const corner = "absolute size-7 border-primary";
  return (
    <>
      <span className={`${corner} top-0 left-0 rounded-tl-2xl border-t-[3px] border-l-[3px]`} />
      <span className={`${corner} top-0 right-0 rounded-tr-2xl border-t-[3px] border-r-[3px]`} />
      <span className={`${corner} bottom-0 left-0 rounded-bl-2xl border-b-[3px] border-l-[3px]`} />
      <span className={`${corner} right-0 bottom-0 rounded-br-2xl border-r-[3px] border-b-[3px]`} />
    </>
  );
}

/** Landing page section: a scannable QR code for the demo shop's live menu. */
export function DemoQr() {
  const t = dict.landing;

  return (
    <section
      id="demo"
      className="reveal relative isolate scroll-mt-24 overflow-hidden rounded-[2rem] bg-[#24150f] px-6 dark:ring-1 dark:ring-white/10 py-12 text-[#f5ebe1] md:px-14 md:py-16"
    >
      <div className="absolute inset-0 -z-10 bg-dots opacity-40 [mask-image:radial-gradient(ellipse_at_left,black,transparent_70%)]" />
      <div className="absolute -right-24 -bottom-32 -z-10 size-96 rounded-full bg-primary/40 blur-3xl" />

      <div className="grid items-center gap-10 md:grid-cols-[auto_1fr] md:gap-14">
        <div className="relative mx-auto size-60 p-4" aria-hidden>
          <Viewfinder />
          <DemoQrCode className="size-full" />
          <span className="absolute inset-x-3 h-0.5 rounded-full bg-primary shadow-[0_0_16px_4px] shadow-primary/60 top-1/2 motion-safe:animate-scan" />
        </div>

        <div className="flex flex-col gap-4 text-center md:text-left">
          <p className="inline-flex items-center gap-2 self-center rounded-full bg-white/10 px-3 py-1 text-sm font-medium ring-1 ring-white/15 md:self-start">
            <span className="relative flex size-2">
              <span className="absolute inline-flex size-full rounded-full bg-emerald-400 opacity-75 motion-safe:animate-ping" />
              <span className="relative inline-flex size-2 rounded-full bg-emerald-400" />
            </span>
            {t.demoBadge}
          </p>
          <h2 className="font-heading text-3xl font-extrabold tracking-tight text-balance md:text-4xl">{t.demoTitle}</h2>
          <p className="max-w-md self-center text-[#f5ebe1]/70 md:self-start">{fill(t.demoText, { shop: DEMO_SHOP.name })}</p>
          <Link
            href={DEMO_PATH}
            target="_blank"
            className={buttonVariants({ size: "lg", className: "mt-2 self-center md:self-start" })}
          >
            <ScanLineIcon data-icon="inline-start" />
            {t.demoOpen}
            <ArrowRightIcon data-icon="inline-end" />
          </Link>
        </div>
      </div>
    </section>
  );
}
